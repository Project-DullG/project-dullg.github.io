  function portraitMarkup(people = []) {
    const images = people
      .filter((name) => portraits[name])
      .map((name) => `<img src="${portraits[name]}" alt="" width="36" height="36">`)
      .join("");
    return images ? `<div class="epilogue-portraits">${images}</div>` : "";
  }

  function blockMarkup(block) {
    if (typeof block === "string") return `<p>${block}</p>`;
    return `<p class="dialogue epilogue-dialogue${block.emphasis ? " dialogue-emphasis" : ""}" data-speaker="${block.speaker}">${block.text}</p>`;
  }

  function titleMarkup(title) {
    return title.split(/(다니엘|애쉬|캔디|류진환)/).map((part) =>
      portraits[part] ? `<span class="character-name" data-character="${part}">${part}</span>` : part
    ).join("");
  }

  function sceneMarkup(scene, index, titleId, standalone = false) {
    const sceneId = standalone ? titleId : `${titleId}-${index + 1}`;
    const headingTag = standalone ? "h2" : "h3";
    const blocks = scene.blocks.map(blockMarkup).join("");
    return [
      `<div class="epilogue-scene epilogue-${scene.tone || "future"}" aria-labelledby="${sceneId}">`,
      '<div class="epilogue-scene-heading">',
      portraitMarkup(scene.people),
      '<div>',
      `<${headingTag} id="${sceneId}">${titleMarkup(scene.title)}</${headingTag}>`,
      `<p class="scene-dateline">${scene.label}</p>`,
      '</div>',
      '</div>',
      blocks,
      '</div>'
    ].join("");
  }

  function appendPage({ kicker, title, intro = "", scenes, modifier = "", standalone = false }, pageIndex) {
    const section = document.createElement("section");
    const titleId = `epilogue-${outcome}-${pageIndex + 1}`;
    const sceneHtml = scenes.map((scene, index) => sceneMarkup(scene, index, titleId, standalone)).join("");

    section.className = `chapter gourmet-epilogue${modifier ? ` ${modifier}` : ""}`;
    section.setAttribute("aria-labelledby", titleId);
    section.innerHTML = standalone ? sceneHtml : [
      `<p class="script-kicker">${kicker}</p>`,
      `<h2 id="${titleId}">${title}</h2>`,
      intro ? `<p class="epilogue-intro">${intro}</p>` : "",
      `<div class="epilogue-scenes">${sceneHtml}</div>`
    ].join("");
    article.appendChild(section);
  }

